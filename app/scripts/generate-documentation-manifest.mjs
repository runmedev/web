import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'
import { parse } from 'yaml'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const appDirectory = resolve(scriptDirectory, '..')
const repositoryDirectory = resolve(appDirectory, '..')
const docsDirectory = resolve(repositoryDirectory, 'docs')
const outputPath = resolve(
  appDirectory,
  'src/generated/documentationManifest.ts'
)
const checkOnly = process.argv.includes('--check')

function parseFrontmatter(fileName, contents) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(contents)
  if (!match) {
    throw new Error(`${fileName}: missing YAML frontmatter`)
  }

  const metadata = parse(match[1])
  if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) {
    throw new Error(`${fileName}: frontmatter must be a YAML mapping`)
  }
  return { body: contents.slice(match[0].length), metadata }
}

function requireString(fileName, metadata, field) {
  const value = metadata[field]
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`${fileName}: ${field} must be a non-empty string`)
  }
  return value.trim()
}

function parseDefinition(fileName, contents) {
  const { body, metadata } = parseFrontmatter(fileName, contents)
  const name = requireString(fileName, metadata, 'name')
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`${fileName}: name must use stable kebab-case`)
  }

  const order = metadata.order
  if (!Number.isSafeInteger(order) || order < 0) {
    throw new Error(`${fileName}: order must be a non-negative integer`)
  }

  const title = requireString(fileName, metadata, 'title')
  const heading = /^#\s+(.+?)\s*$/m.exec(body)?.[1]
  if (heading !== title) {
    throw new Error(
      `${fileName}: title ${JSON.stringify(title)} must match its first level-one heading`
    )
  }

  return {
    name,
    title,
    description: requireString(fileName, metadata, 'description'),
    order,
    path: `docs/${fileName}`,
  }
}

function assertUnique(definitions, field) {
  const seen = new Map()
  for (const definition of definitions) {
    const value = definition[field]
    const existing = seen.get(value)
    if (existing) {
      throw new Error(
        `Duplicate documentation ${field} ${JSON.stringify(value)} in ${existing} and ${definition.path}`
      )
    }
    seen.set(value, definition.path)
  }
}

function renderManifest(definitions) {
  const entries = definitions
    .map(
      (definition) =>
        `  ${JSON.stringify(definition, null, 2).split('\n').join('\n  ')},`
    )
    .join('\n')

  return `// Generated by app/scripts/generate-documentation-manifest.mjs.
// Edit docs/*.md frontmatter, then run: pnpm generate:documentation

export type DocumentationManifestEntry = {
  readonly name: string
  readonly title: string
  readonly description: string
  readonly order: number
  readonly path: string
}

export const DOCUMENTATION_MANIFEST = [
${entries}
] as const satisfies readonly DocumentationManifestEntry[]
`
}

const fileNames = (await readdir(docsDirectory))
  .filter((fileName) => fileName.endsWith('.md') && fileName !== 'README.md')
  .sort()
const definitions = await Promise.all(
  fileNames.map(async (fileName) =>
    parseDefinition(
      fileName,
      await readFile(resolve(docsDirectory, fileName), 'utf8')
    )
  )
)
definitions.sort((left, right) => left.order - right.order)
assertUnique(definitions, 'name')
assertUnique(definitions, 'order')

const generated = await format(renderManifest(definitions), {
  ...(await resolveConfig(outputPath)),
  filepath: outputPath,
})

if (checkOnly) {
  let existing = ''
  try {
    existing = await readFile(outputPath, 'utf8')
  } catch {
    // The error below gives the actionable regeneration command.
  }
  if (existing !== generated) {
    throw new Error(
      'Documentation manifest is stale. Run: pnpm generate:documentation'
    )
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated)
}
