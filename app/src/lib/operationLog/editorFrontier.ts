import type { MaterializedOperationLog } from './materialize'
import { causalHeads } from './mutations'
import { committedOperationIds } from './order'
import { comparePositionIds, validatePositionId } from './positions'
import type {
  CellCreatePayload,
  ExecutionStartPayload,
  PositionId,
  RunmeOperation,
} from './types'

/** Data needed to diff a private editor baseline. Historical source and output
 * bodies are already represented by the current notebook or by the journal. */
export interface EditorFrontier {
  heads: string[]
  lamport: number
  sequences: Map<string, number>
  cells: Map<string, { position: PositionId; source: string }>
  createdIds: Set<string>
  starts: Map<string, string>
}

/** Pending dependencies can become visible after a later edit. Keep the full
 * replay path for that case and for histories with incomplete transactions. */
export function editorFrontier(
  ops: RunmeOperation[],
  view: MaterializedOperationLog
): EditorFrontier | undefined {
  if (committedOperationIds(ops).size !== ops.length) return undefined
  const sequences = new Map<string, number>()
  const createdIds = new Set<string>()
  for (const op of ops) {
    sequences.set(
      op.actor_id,
      Math.max(sequences.get(op.actor_id) ?? 0, op.actor_seq)
    )
    if (op.kind === 'cell.create')
      createdIds.add((op.payload as unknown as CellCreatePayload).cell_id)
  }
  return {
    heads: causalHeads(ops),
    lamport: ops.reduce((n, op) => Math.max(n, op.lamport), 0),
    sequences,
    createdIds,
    cells: new Map(
      view.notebook.cells.map((c) => [
        c.cell_id,
        { position: c.position, source: c.source_operation_id },
      ])
    ),
    starts: new Map(
      view.executions.map((e) => [e.execution_id, e.start.cell_id])
    ),
  }
}

/** Only called with the linear batch generated by this editor, after durable
 * acknowledgement. Remote operations must never advance a private baseline. */
export function advanceEditorFrontier(
  frontier: EditorFrontier,
  batch: RunmeOperation[]
) {
  for (const op of batch) {
    const p = op.payload as unknown as CellCreatePayload
    const cell = frontier.cells.get(p.cell_id)
    switch (op.kind) {
      case 'cell.create':
        frontier.createdIds.add(p.cell_id)
        frontier.cells.set(p.cell_id, {
          position: p.position,
          source: op.op_id,
        })
        break
      case 'cell.restore':
        // buildOperationLogDiff immediately follows a restore with cell.update.
        frontier.cells.set(p.cell_id, {
          position: p.position,
          source: op.op_id,
        })
        break
      case 'cell.update':
        if (cell) cell.source = op.op_id
        break
      case 'cell.move':
        if (cell) cell.position = p.position
        break
      case 'cell.delete':
        frontier.cells.delete(p.cell_id)
        break
      case 'execution.start': {
        const run = op.payload as unknown as ExecutionStartPayload
        if (!frontier.starts.has(run.execution_id))
          frontier.starts.set(run.execution_id, run.cell_id)
        break
      }
    }
    frontier.sequences.set(op.actor_id, op.actor_seq)
    frontier.lamport = op.lamport
    frontier.heads = [op.op_id]
  }
  frontier.cells = new Map(
    [...frontier.cells].sort(
      ([a, left], [b, right]) =>
        comparePositionIds(left.position, right.position) ||
        (a < b ? -1 : a > b ? 1 : 0)
    )
  )
}

/** Encode Maps as tuples so arbitrary actor/cell IDs survive JSON checkpoints. */
export function packFrontier(f: EditorFrontier) {
  return {
    heads: f.heads,
    lamport: f.lamport,
    sequences: [...f.sequences],
    cells: [...f.cells],
    createdIds: [...f.createdIds],
    starts: [...f.starts],
  }
}
export type PackedFrontier = ReturnType<typeof packFrontier>
export function unpackFrontier(f: PackedFrontier): EditorFrontier {
  if (
    !Array.isArray(f.heads) ||
    !f.heads.every((id) => typeof id === 'string') ||
    !Number.isSafeInteger(f.lamport) ||
    f.lamport < 0 ||
    ![f.cells, f.createdIds, f.sequences, f.starts].every(Array.isArray) ||
    !f.createdIds.every((id) => typeof id === 'string') ||
    !f.cells.every(
      ([id, c]) => typeof id === 'string' && typeof c?.source === 'string'
    ) ||
    !f.starts.every(
      ([run, cell]) => typeof run === 'string' && typeof cell === 'string'
    ) ||
    !f.sequences.every(
      ([id, n]) => typeof id === 'string' && Number.isSafeInteger(n) && n > 0
    )
  )
    throw new Error('Invalid editor frontier')
  for (const [, cell] of f.cells) validatePositionId(cell.position)
  return {
    ...f,
    sequences: new Map(f.sequences),
    cells: new Map(f.cells.map(([id, c]) => [id, { ...c }])),
    createdIds: new Set(f.createdIds),
    starts: new Map(f.starts),
  }
}
